# Lookup dictionary by uppercase alpha-2 code
COUNTRY_MAP: dict[str, CountryCatalogEntry] = {entry["code"]: entry for entry in COUNTRY_CATALOG}

# Official frozenset of valid 2-letter uppercase codes (derived directly from catalog)
ISO_COUNTRY_CODES: frozenset[str] = frozenset(COUNTRY_MAP.keys())


def is_valid_iso_country(code: str) -> bool:
    """Validate whether code is a valid ISO 3166-1 alpha-2 code."""
    return code.upper() in ISO_COUNTRY_CODES


def get_country_by_code(code: str) -> CountryCatalogEntry | None:
    """Get country catalog entry by 2-letter code."""
    return COUNTRY_MAP.get(code.upper())
